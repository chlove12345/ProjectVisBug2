let language = 'en'
const originals = new WeakMap()
const originalAttributes = new WeakMap()
const messages = {
  en: {name: 'English', toolAriaLabel: '{name} Tool', moveCorner: 'Move corner {number}'},
  'zh-CN': {name: '简体中文', toolAriaLabel: '{name}工具', moveCorner: '移动角点 {number}'},
}
const phrases = {en: {}, 'zh-CN': chinese}
const normalizedLanguage = value =>
  Object.prototype.hasOwnProperty.call(messages, value) ? value : 'en'

export const languageOptions = Object.entries(messages)
  .map(([value, {name}]) => ({value, name}))

export const getLanguage = () => language

export const getSavedLanguage = () => {
  if (document.querySelector('vis-bug')?.hasAttribute('extension')) return 'en'
  try { return normalizedLanguage(localStorage.getItem('visbug-language')) }
  catch { return 'en' }
}

export const setLanguage = (next, persist = false) => {
  const normalized = normalizedLanguage(next)
  if (persist && !document.querySelector('vis-bug')?.hasAttribute('extension')) {
    try { localStorage.setItem('visbug-language', normalized) }
    catch {}
  }
  if (language === normalized) return
  language = normalized
  document.dispatchEvent(new Event('visbug-language-change'))
}

export const translate = text =>
  phrases[language][text] || text

export const message = (key, values = {}) => {
  const template = messages[language][key] || messages.en[key] || key
  return template.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? '')
}

export const toolPresentation = tool => {
  const originalName = tool.label.replace(/<[^>]*>/g, '')
  const originalDescription = tool.description.replace(/<[^>]*>/g, '')
  const name = translate(originalName)
  const description = translate(originalDescription)

  return {
    ariaLabel: message('toolAriaLabel', {name}),
    ariaDescription: description,
    labelHtml: name === originalName ? tool.label : name,
    descriptionHtml: description === originalDescription ? tool.description : description,
  }
}

const localizeValue = (node, value) => {
  const previous = originals.get(node)
  const source = previous?.translated === value ? previous.source : value
  const prefix = source.match(/^\s*/)[0]
  const suffix = source.match(/\s*$/)[0]
  const translated = prefix + translate(source.trim()) + suffix
  originals.set(node, {source, translated})
  return translated
}

export const localize = root => {
  if (!root) return
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
  while (walker.nextNode()) {
    const node = walker.currentNode
    const translated = localizeValue(node, node.nodeValue)
    if (translated !== node.nodeValue) node.nodeValue = translated
  }

  root.querySelectorAll?.('[aria-label], [aria-description], [title], [placeholder]').forEach(node => {
    let attributes = originalAttributes.get(node)
    if (!attributes) {
      attributes = {}
      originalAttributes.set(node, attributes)
    }
    for (const name of ['aria-label', 'aria-description', 'title', 'placeholder']) {
      if (!node.hasAttribute(name)) continue
      const value = node.getAttribute(name)
      if (!attributes[name] || attributes[name].translated !== value)
        attributes[name] = {source: value}
      const translated = translate(attributes[name].source)
      attributes[name].translated = translated
      if (translated !== value) node.setAttribute(name, translated)
    }
  })

  root.querySelectorAll?.('[data-i18n-aria-label]').forEach(node => {
    node.setAttribute('aria-label', message(node.dataset.i18nAriaLabel, {
      number: node.dataset.i18nNumber,
    }))
  })
}
